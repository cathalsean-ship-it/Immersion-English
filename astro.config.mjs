import { defineConfig } from 'astro/config';
import tailwind from '@astrojs/tailwind';
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

// Serve every page at both /page and /page/ with a 200 (no redirect).
//
// Why: until 16 Oct 2026 Netlify answered /lessons with a PERMANENT redirect
// to /lessons/. Browsers cache permanent redirects. Once the site switched to
// /lessons (format 'file' below), Netlify began redirecting /lessons/ ->
// /lessons, and those browsers bounced between the two until they showed
// ERR_TOO_MANY_REDIRECTS. Netlify's own slash tidying ignores page/index.html
// copies, so instead this writes a _redirects file with one forced 200
// REWRITE per page (not a redirect). Netlify matches rules with and without a
// trailing slash, so both forms get the page and there is nothing to loop.
// Search engines still see one page: its canonical tag says /lessons.
//
// Rules are generated from the built pages, one per page, never a wildcard:
// a catch-all rule once sent every missing URL into an infinite loop (see
// netlify.toml). Do not remove this while any visitor may still have the old
// redirect cached, which for some browsers is indefinitely.
const slashRewrites = {
  name: 'slash-rewrites',
  hooks: {
    'astro:build:done': ({ dir }) => {
      const root = fileURLToPath(dir);
      const rules = [];
      const walk = (d) => {
        for (const name of readdirSync(d)) {
          const p = join(d, name);
          if (statSync(p).isDirectory()) { if (!['_astro', 'og', 'fonts', 'nci-gallery'].includes(name)) walk(p); continue; }
          if (!name.endsWith('.html')) continue;
          const rel = relative(root, p).split(sep).join('/');
          if (rel === 'index.html' || rel === '404.html') continue;
          const path = '/' + rel.slice(0, -5);
          rules.push(`${path}  /${rel}  200!`);
        }
      };
      walk(root);
      rules.sort();
      writeFileSync(join(root, '_redirects'), '# Generated by astro.config.mjs (slash-rewrites). Do not edit.\n' + rules.join('\n') + '\n');
    },
  },
};

export default defineConfig({
  site: 'https://immersion-english.com',
  trailingSlash: 'never',
  // Inline the (small) stylesheet so it doesn't block first paint.
  //
  // 'file' builds /lessons as lessons.html (not lessons/index.html), so Netlify
  // serves /lessons directly with a 200 instead of redirecting to /lessons/.
  // Every canonical, og:url, sitemap entry and internal link uses the
  // no-slash form; this keeps the server consistent with them.
  build: { inlineStylesheets: 'always', format: 'file' },
  integrations: [
    tailwind(),
    slashRewrites,
  ],
  vite: {
    build: {
      cssCodeSplit: false,
      rollupOptions: {
        output: {
          manualChunks: undefined,
        }
      }
    }
  }
});
